"""Generate ctypes struct mirrors for CUI option/data structs from ``cui.h``.

Used to keep ``src/nexa/_abi14.py`` in step with ``csrc/include/cui/`` when the
upstream CUI engine is re-synced.  Only plain C data structs are emitted; a
struct whose fields use an unknown type, a nested anonymous aggregate or an
anonymous function pointer is reported on stderr and left for a hand-written
mirror.

Usage::

    python tools/gen_abi.py            # structs not yet mirrored in nexa
    python tools/gen_abi.py --all      # every struct in the headers
    python tools/gen_abi.py --out src/nexa/_abi14.py
"""

from __future__ import annotations

import argparse
import ctypes
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HEADERS = ("cui.h", "cui_app.h", "cui_render.h")

SCALARS = {
    "bool": "c_bool",
    "char": "c_char",
    "int": "c_int",
    "unsigned": "c_uint",
    "unsigned int": "c_uint",
    "float": "c_float",
    "double": "c_double",
    "size_t": "c_size_t",
    "uint8_t": "c_uint8",
    "uint16_t": "c_uint16",
    "uint32_t": "c_uint32",
    "uint64_t": "c_uint64",
    "int32_t": "c_int32",
    "int64_t": "c_int64",
    "void": "c_void_p",
}

STRUCT_ALIASES = {"cui_id": "c_uint32", "cui_texture": "c_size_t"}

HEADER_TEMPLATE = '''"""ctypes struct mirrors for CUI components added after the 1.1 port.

Generated by ``tools/gen_abi.py`` from ``csrc/include/cui/``; do not edit by hand.
"""

from __future__ import annotations

from ctypes import (
    POINTER,
    Structure,
    c_bool,
    c_char,
    c_char_p,
    c_double,
    c_float,
    c_int,
    c_int32,
    c_int64,
    c_size_t,
    c_uint,
    c_uint8,
    c_uint16,
    c_uint32,
    c_uint64,
    c_void_p,
)

{imports}'''

IMPORT_PLACEHOLDER = "from ._cdefs import (\n{names}\n)\n"


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", " ", text)


def parse_enums(text: str) -> dict[str, dict[str, int | None]]:
    out: dict[str, dict[str, int | None]] = {}
    for m in re.finditer(r"typedef\s+enum\s*\w*\s*\{([^}]*)\}\s*(\w+)\s*;", text, flags=re.S):
        items: dict[str, int | None] = {}
        value = 0
        for part in m.group(1).split(","):
            part = part.strip()
            if not part:
                continue
            if "=" in part:
                key, raw = part.split("=", 1)
                key = key.strip()
                try:
                    value = int(raw.strip(), 0)
                except ValueError:
                    value = None
            else:
                key = part
            items[key] = value
            if value is not None:
                value += 1
        out[m.group(2)] = items
    return out


def parse_fn_typedefs(text: str) -> set[str]:
    return set(re.findall(r"typedef\s+[\w\s*]*\(\s*\*\s*(\w+)\s*\)\s*\(", text))


def parse_structs(text: str) -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for m in re.finditer(r"typedef\s+struct\s*(\w+)?\s*\{", text):
        start = m.end()
        depth, j = 1, start
        while depth and j < len(text):
            if text[j] == "{":
                depth += 1
            elif text[j] == "}":
                depth -= 1
            j += 1
        body = text[start : j - 1]
        tail = re.match(r"\s*(\w+)\s*;", text[j : j + 80])
        if tail:
            found.append((tail.group(1), body))
    return found


def split_fields(body: str) -> list[str]:
    out, cur, depth = [], "", 0
    for ch in body:
        if ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == ";" and depth == 0:
            out.append(" ".join(cur.split()))
            cur = ""
        else:
            cur += ch
    return [f for f in out if f]


def camel(c_name: str) -> str:
    return "Cui" + "".join(p.capitalize() for p in c_name.split("_")[1:])


def field_pairs(decl: str) -> list[tuple[str, str]]:
    """Split ``float a, b[4]`` style declarations into ``(ctype, name)`` pairs.

    Array suffixes stay attached to the field name so the ctypes declaration can
    keep them (``c_char * 64``).
    """
    decl = " ".join(decl.split())
    parts = [p.strip() for p in decl.split(",")]
    m = re.match(r"^(.*?[\s*])([A-Za-z_]\w*(?:\[\d+\])*)$", parts[0])
    if not m:
        return []
    base, first = m.group(1).strip(), m.group(2)
    pairs = [(base, first)]
    for extra in parts[1:]:
        extra = extra.strip()
        stars = "*" * extra.count("*")
        name = extra.replace("*", " ").strip()
        if not re.fullmatch(r"[A-Za-z_]\w*(?:\[\d+\])*", name):
            return []
        pairs.append((f"{base.rstrip('*').strip()} {stars}".strip(), name))
    return pairs


def ctypes_type(decl: str, enum_names: set[str], known: set[str], fn_typedefs: set[str]) -> str | None:
    decl = " ".join(decl.split())
    if "(" in decl:  # anonymous function pointer
        return "c_void_p"
    array = None
    m = re.match(r"^(.*?)\[(\d+)\]$", decl)
    if m:
        decl, array = m.group(1).strip(), int(m.group(2))
    stars = decl.count("*")
    base = " ".join(decl.replace("*", " ").split())
    const = base.startswith("const ")
    bare = base[6:].strip() if const else base

    if stars == 2:
        py = "POINTER(c_char_p)" if bare.startswith("char") else None
    elif stars == 1:
        if bare.startswith("char"):
            py = "c_char_p"
        elif bare.startswith("void"):
            py = "c_void_p"
        elif bare.startswith("cui_"):
            target = camel(bare)
            py = f"POINTER({target})" if target in known else "c_void_p"
        else:
            scalar = SCALARS.get(bare)
            py = f"POINTER({scalar})" if scalar and scalar != "c_void_p" else "c_void_p"
    elif bare in fn_typedefs:
        py = "c_void_p"
    elif bare in enum_names:
        py = "c_int"
    elif bare in STRUCT_ALIASES:
        py = STRUCT_ALIASES[bare]
    elif bare in SCALARS:
        py = SCALARS[bare]
    elif bare.startswith("cui_"):
        target = camel(bare)
        py = target if target in known else None
    else:
        py = None

    if py is None:
        return None
    return f"{py} * {array}" if array is not None else py


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--all", action="store_true", help="emit every struct in the headers")
    ap.add_argument("--out", default=None, help="write here instead of stdout")
    args = ap.parse_args(argv)

    text = strip_comments(
        "\n".join((ROOT / "csrc" / "include" / "cui" / h).read_text(encoding="utf-8") for h in HEADERS)
    )
    enum_names = set(parse_enums(text))
    fn_typedefs = parse_fn_typedefs(text)
    structs = parse_structs(text)

    sys.path.insert(0, str(ROOT / "src"))
    from nexa import _cdefs  # noqa: PLC0415

    mirrored = {
        name
        for name in dir(_cdefs)
        if isinstance(getattr(_cdefs, name), type) and issubclass(getattr(_cdefs, name), ctypes.Structure)
    }
    wanted = None
    if not args.all:
        generated_before: set[str] = set()
        try:
            from nexa import _abi14  # noqa: PLC0415

            generated_before = {n for n in dir(_abi14) if n.startswith("Cui")}
        except Exception:
            pass
        wanted = {camel(n) for n, _ in structs} - mirrored - generated_before

    known = set(mirrored)
    generated: set[str] = set()
    used_existing: set[str] = set()
    chunks: list[str] = []
    skipped: list[str] = []

    for cname, body in structs:
        py_name = camel(cname)
        if wanted is not None and py_name not in wanted:
            continue
        fields: list[str] = []
        ok = True
        for decl in split_fields(body):
            if "{" in decl or "}" in decl:
                ok = False
                break
            pairs = field_pairs(decl)
            if not pairs:
                ok = False
                break
            for ctype, fname in pairs:
                py = ctypes_type(ctype, enum_names, known | generated, fn_typedefs)
                if py is None:
                    ok = False
                    break
                for ref in re.findall(r"\b(Cui\w+)\b", py):
                    if ref in mirrored:
                        used_existing.add(ref)
                arr = re.match(r"^(\w+)((?:\[\d+\])*)$", fname)
                if arr and arr.group(2):
                    dims = "".join(f" * {d}" for d in re.findall(r"\[(\d+)\]", arr.group(2)))
                    fields.append(f'        ("{arr.group(1)}", {py}{dims}),')
                else:
                    fields.append(f'        ("{fname}", {py}),')
            if not ok:
                break
        if not ok or not fields:
            skipped.append(cname)
            continue
        chunks.append(f"class {py_name}(Structure):\n    _fields_ = [\n" + "\n".join(fields) + "\n    ]\n")
        generated.add(py_name)

    imports = ""
    if used_existing:
        imports = IMPORT_PLACEHOLDER.format(names="\n".join(f"    {n}," for n in sorted(used_existing)))
    out = HEADER_TEMPLATE.format(imports=imports) + "\n".join(chunks)

    if args.out:
        Path(args.out).write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out)
    for name in skipped:
        print(f"# skipped (write by hand): {name}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
